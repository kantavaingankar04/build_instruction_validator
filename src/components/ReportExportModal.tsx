import React, { useState } from 'react';
import { X, FileText, Download, Code, Printer, Check, Copy } from 'lucide-react';
import { ValidationReport } from '../types/validator';
// @ts-ignore
import html2pdf from 'html2pdf.js';

interface ReportExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  report: ValidationReport;
}

export const ReportExportModal: React.FC<ReportExportModalProps> = ({
  isOpen,
  onClose,
  report
}) => {
  if (!isOpen) return null;

  const [activeFormat, setActiveFormat] = useState<'html' | 'markdown' | 'json' | 'pdf'>('html');
  const [copied, setCopied] = useState(false);

  // 1. Generate Markdown
  const generateMarkdown = () => {
    return `# Linux on IBM Z (s390x) Build Instruction Discrepancy Report

- **Package**: ${report.packageName} (${report.packageVersion})
- **Target OS / Architecture**: ${report.distroTarget}
- **Timestamp**: ${report.timestamp}
- **Overall Compliance Score**: **${report.complianceScore}%**

---

## Executive Summary
${report.summary}

---

## Validation KPI Metrics
- **Documented Steps in BI**: ${report.totalExpectedSteps}
- **Matched Steps**: ${report.matchedSteps}
- **Missing Steps in Script**: ${report.missingSteps}
- **Parameter Mismatches**: ${report.parameterMismatches}
- **Version Inconsistencies**: ${report.versionInconsistencies}
- **Additional Undocumented Script Steps**: ${report.additionalSteps}

---

## Classified Discrepancies
${report.discrepancies
  .map(
    (d, i) => `### ${i + 1}. [${d.severity}] ${d.title}
- **Category**: \`${d.type}\`
- **Description**: ${d.description}
- **Documented in BI**: \`${d.biReference || 'N/A'}\`
- **Executed in Script**: \`${d.scriptReference || 'N/A'}\`
- **IBM Z (s390x) Impact**: ${d.impact}
- **Recommended Remediation**: ${d.remediation}
${d.suggestedPatchSnippet ? `\`\`\`bash\n${d.suggestedPatchSnippet}\n\`\`\`` : ''}
`
  )
  .join('\n')}

---

## Remediated Bash Script for IBM Z
\`\`\`bash
${report.suggestedRemediationScript}
\`\`\`

---
*Report generated by Linux on IBM Z AI Assistant for Build Instruction Validation.*
`;
  };

  // 2. Generate Standalone Styled HTML
  const generateHtml = () => {
    const md = generateMarkdown();
    return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Build Instruction Discrepancy Report - ${report.packageName} ${report.packageVersion}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; background: #0f172a; color: #e2e8f0; padding: 40px 20px; line-height: 1.6; max-width: 900px; margin: 0 auto; }
    h1 { color: #60a5fa; border-bottom: 2px solid #1e293b; padding-bottom: 12px; }
    h2 { color: #93c5fd; margin-top: 32px; border-bottom: 1px solid #1e293b; padding-bottom: 8px; }
    h3 { color: #38bdf8; margin-top: 24px; }
    .score-badge { display: inline-block; font-size: 28px; font-weight: bold; padding: 12px 24px; border-radius: 12px; background: #1e1b4b; border: 2px solid #6366f1; color: #a5b4fc; margin-bottom: 20px; font-family: monospace; }
    .kpi-grid { display: grid; grid-template-columns: repeat(auto-fit, minmax(130px, 1fr)); gap: 12px; margin: 20px 0; }
    .kpi-card { background: #1e293b; padding: 12px; border-radius: 8px; text-align: center; border: 1px solid #334155; }
    .kpi-val { font-size: 20px; font-weight: bold; font-family: monospace; color: #38bdf8; }
    .kpi-lbl { font-size: 11px; color: #94a3b8; text-transform: uppercase; }
    .discrepancy-card { background: #1e293b; border: 1px solid #334155; border-radius: 10px; padding: 16px; margin-bottom: 16px; }
    .badge-critical { background: #450a0a; color: #f87171; padding: 3px 8px; border-radius: 4px; font-size: 11px; font-weight: bold; border: 1px solid #ef4444; }
    .badge-warning { background: #451a03; color: #fbbf24; padding: 3px 8px; border-radius: 4px; font-size: 11px; font-weight: bold; border: 1px solid #f59e0b; }
    .badge-info { background: #082f49; color: #38bdf8; padding: 3px 8px; border-radius: 4px; font-size: 11px; font-weight: bold; border: 1px solid #0ea5e9; }
    pre { background: #090d16; padding: 14px; border-radius: 8px; overflow-x: auto; color: #a7f3d0; font-size: 12px; border: 1px solid #1e293b; font-family: monospace; }
    code { font-family: monospace; background: #090d16; padding: 2px 6px; border-radius: 4px; color: #f1f5f9; }
    @media print { body { background: #fff; color: #000; } .kpi-card, .discrepancy-card, pre { border-color: #ccc; background: #fafafa; color: #000; } }
  </style>
</head>
<body>
  <h1>Linux on IBM Z: Build Instruction Discrepancy Report</h1>
  <p><strong>Package:</strong> ${report.packageName} (${report.packageVersion}) | <strong>Architecture:</strong> ${report.distroTarget}</p>
  
  <div class="score-badge">Overall Compliance: ${report.complianceScore}%</div>

  <div class="kpi-grid">
    <div class="kpi-card"><div class="kpi-val">${report.totalExpectedSteps}</div><div class="kpi-lbl">Total Steps</div></div>
    <div class="kpi-card"><div class="kpi-val" style="color: #4ade80;">${report.matchedSteps}</div><div class="kpi-lbl">Matched</div></div>
    <div class="kpi-card"><div class="kpi-val" style="color: #f87171;">${report.missingSteps}</div><div class="kpi-lbl">Missing</div></div>
    <div class="kpi-card"><div class="kpi-val" style="color: #fbbf24;">${report.parameterMismatches}</div><div class="kpi-lbl">Params</div></div>
    <div class="kpi-card"><div class="kpi-val" style="color: #818cf8;">${report.versionInconsistencies}</div><div class="kpi-lbl">Versions</div></div>
  </div>

  <h2>Executive Summary</h2>
  <p>${report.summary}</p>

  <h2>Classified Discrepancies (${report.discrepancies.length})</h2>
  ${report.discrepancies
    .map(
      d => `
    <div class="discrepancy-card">
      <div style="display:flex; justify-content:space-between; align-items:center; margin-bottom:8px;">
        <strong style="color:#fff; font-size:15px;">${d.title}</strong>
        <span class="${d.severity === 'CRITICAL' ? 'badge-critical' : d.severity === 'WARNING' ? 'badge-warning' : 'badge-info'}">${d.severity}</span>
      </div>
      <p style="margin:4px 0 10px 0; color:#cbd5e1; font-size:13px;">${d.description}</p>
      <div style="margin:8px 0; font-size:12px;"><strong>BI Documentation:</strong> <code>${d.biReference || 'N/A'}</code></div>
      <div style="margin:8px 0; font-size:12px;"><strong>Script Execution:</strong> <code>${d.scriptReference || 'N/A'}</code></div>
      <p style="font-size:12px; color:#c7d2fe; margin-top:8px;"><strong>s390x Impact:</strong> ${d.impact}</p>
      <p style="font-size:12px; color:#fde68a; margin-top:4px;"><strong>Remediation:</strong> ${d.remediation}</p>
      ${d.suggestedPatchSnippet ? `<pre><code>${d.suggestedPatchSnippet}</code></pre>` : ''}
    </div>`
    )
    .join('')}

  <h2>Remediated Build Script</h2>
  <pre><code>${report.suggestedRemediationScript}</code></pre>
  
  <p style="margin-top:40px; font-size:11px; color:#64748b; text-align:center;">
    Report synthesized via Linux on IBM Z AI Assistant • Mentorship Mini-Project
  </p>
</body>
</html>`;
  };

  const getExportContent = () => {
    switch (activeFormat) {
      case 'html': 
      case 'pdf': return generateHtml();
      case 'markdown': return generateMarkdown();
      case 'json': return JSON.stringify(report, null, 2);
    }
  };

  const handleDownload = () => {
    if (activeFormat === 'pdf') {
      const parser = new DOMParser();
      const doc = parser.parseFromString(generateHtml(), 'text/html');
      const element = doc.body;
      const opt = {
        margin:       10,
        filename:     `discrepancy_report_${report.packageName.toLowerCase().replace(/\s+/g, '_')}.pdf`,
        image:        { type: 'jpeg' as const, quality: 0.98 },
        html2canvas:  { scale: 2 },
        jsPDF:        { unit: 'mm', format: 'a4', orientation: 'portrait' as const }
      };
      html2pdf().set(opt).from(element).save();
      return;
    }

    const content = getExportContent();
    const mimeTypes: any = {
      html: 'text/html',
      markdown: 'text/markdown',
      json: 'application/json'
    };
    const extensions: any = {
      html: 'html',
      markdown: 'md',
      json: 'json'
    };

    const blob = new Blob([content], { type: mimeTypes[activeFormat] });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `discrepancy_report_${report.packageName.toLowerCase().replace(/\s+/g, '_')}.${extensions[activeFormat]}`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(getExportContent());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm overflow-y-auto">
      <div className="glass-panel-elevated rounded-2xl w-full max-w-2xl border border-slate-700 p-6 shadow-2xl relative my-8">
        <button
          onClick={onClose}
          className="absolute top-5 right-5 text-slate-400 hover:text-white p-1 rounded-lg hover:bg-slate-800 transition"
        >
          <X className="w-5 h-5" />
        </button>

        <div className="flex items-center space-x-3 mb-5">
          <div className="w-10 h-10 rounded-lg bg-blue-600 flex items-center justify-center text-white shadow-md">
            <FileText className="w-5 h-5" />
          </div>
          <div>
            <h3 className="text-lg font-bold text-white">
              Export Discrepancy Report
            </h3>
            <p className="text-xs text-slate-400">
              Download formatted audit documentation in HTML, Markdown, or JSON formats
            </p>
          </div>
        </div>

        {/* Format tabs */}
        <div className="flex items-center justify-between pb-3 border-b border-slate-800">
          <div className="flex items-center bg-slate-900 rounded-lg p-1 border border-slate-800 text-xs">
            <button
              onClick={() => setActiveFormat('html')}
              className={`px-3 py-1.5 rounded-md font-medium transition ${
                activeFormat === 'html' ? 'bg-blue-600 text-white' : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              Styled HTML Report
            </button>
            <button
              onClick={() => setActiveFormat('markdown')}
              className={`px-3 py-1.5 rounded-md font-medium transition ${
                activeFormat === 'markdown' ? 'bg-blue-600 text-white' : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              Markdown (.md)
            </button>
            <button
              onClick={() => setActiveFormat('json')}
              className={`px-3 py-1.5 rounded-md font-medium transition ${
                activeFormat === 'json' ? 'bg-blue-600 text-white' : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              JSON Raw
            </button>
            <button
              onClick={() => setActiveFormat('pdf')}
              className={`px-3 py-1.5 rounded-md font-medium transition ${
                activeFormat === 'pdf' ? 'bg-blue-600 text-white' : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              PDF
            </button>
          </div>

          <div className="flex items-center space-x-2">
            <button
              onClick={handleCopy}
              className="px-2.5 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-xs text-slate-200 border border-slate-700 flex items-center space-x-1 transition"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="px-3.5 py-1.5 rounded-lg bg-blue-600 hover:bg-blue-500 text-xs font-semibold text-white shadow-md flex items-center space-x-1.5 transition"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download File</span>
            </button>
          </div>
        </div>

        {/* Preview Container */}
        <div className="mt-4 rounded-xl overflow-hidden border border-slate-800 bg-[#070b12] p-4 max-h-[360px] overflow-y-auto">
          <pre className="text-xs font-mono text-slate-300 whitespace-pre-wrap leading-relaxed">
            {getExportContent()}
          </pre>
        </div>
      </div>
    </div>
  );
};
